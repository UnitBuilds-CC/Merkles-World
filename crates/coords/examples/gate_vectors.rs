//! Emits the gate C2 test vectors as Rust constants. Run it on a new target to check that the
//! literals in `tests/gates.rs::c2_test_vectors_are_frozen` still hold, or to regenerate them when
//! the lattice function is deliberately changed.

use coords::lattice::lattice_hash;
use coords::GlobalVoxelPos;

fn main() {
    let vectors: [(u64, [i64; 3]); 6] = [
        (0, [0, 0, 0]),
        (0, [50_000_000, 64, -12_000_000]),
        (1, [0, 0, 0]),
        (0x5eed_1234_cafe_f00d, [-1, -2, -3]),
        (0xffff_ffff_ffff_ffff, [1 << 33, -(1 << 33), 4095]),
        (0x5eed, [50_000_000, 64, -12_000_000]),
    ];
    println!("// generated by `cargo run --example gate_vectors` on this target");
    for (i, &(seed, [x, y, z])) in vectors.iter().enumerate() {
        let p = GlobalVoxelPos { x, y, z };
        println!(
            "const V{i}: u64 = {:#018x};  // seed {seed:#018x}, [{x}, {y}, {z}]",
            lattice_hash(seed, &p)
        );
    }
}

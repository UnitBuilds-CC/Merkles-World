//! Publishes the A-10 root vectors: the digests every implementation must reproduce bitwise.
//!
//! Run with `cargo run --release --example root_vectors -p ledger`. The literals it prints are the
//! same ones `tests/root_vectors.rs` pins, and CI runs this on x86-64 Linux, x86-64 Windows and
//! ARM64 macOS — which is the first time in this repo that the *same* epoch root has been computed on
//! more than one architecture. That is gate P1.5's shape, at three of its four targets: the fourth
//! (M1-browser, via WASM) needs a runner, which is OQ-41.
//!
//! This is a printer, not a check: it cannot fail. The assertion half lives in the test.

use contracts::coords::{LocalOffset, RegionKey};
use contracts::delta::{DeltaRecord, EpochHeader, RegionSlot};
use ledger::{
    epoch_root, event_leaf, genesis_root, list_root, region_leaf, region_root, slot_leaves,
    voxel_leaf, EmptyLadder, Leaf, Root,
};

fn hex(root: &Root) -> String {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(root.len() * 2);
    for byte in root {
        out.push(DIGITS[(byte >> 4) as usize] as char);
        out.push(DIGITS[(byte & 0x0f) as usize] as char);
    }
    out
}

fn main() {
    let ladder = EmptyLadder::compute();

    // The scenario is small enough to rebuild by hand, which is the point: a vector nobody can trace
    // by eye is a number, not evidence.
    const SEED: u64 = 0x5EED_0000_0000_0001;
    let genesis = genesis_root(SEED, 0, 0);

    // ADR-029's slot table, deliberately across a negative region coordinate: slot 0 is the origin
    // region, slot 1 is `(-1, 2, 0)`, so the `i64` little-endian encoding is exercised on both sides
    // of zero.
    const SLOTS: [RegionKey; 2] = [
        RegionKey { x: 0, y: 0, z: 0 },
        RegionKey { x: -1, y: 2, z: 0 },
    ];

    // Three edits in region slot 0, one at each octant extreme and one in the interior. Deliberately
    // handed over in *arrival* order rather than walk order, so the printer proves the root is
    // position-keyed.
    let records = [
        DeltaRecord::new(
            RegionSlot(0),
            LocalOffset {
                x: 2048,
                y: 0,
                z: 4095,
            },
            0x7,
        ),
        DeltaRecord::new(RegionSlot(0), LocalOffset { x: 0, y: 0, z: 0 }, 0x1),
        DeltaRecord::new(
            RegionSlot(0),
            LocalOffset {
                x: 4095,
                y: 4095,
                z: 4095,
            },
            0x0ABC,
        ),
    ];
    let mut leaves: [Leaf; 3] = [
        Leaf::from_record(records[0]),
        Leaf::from_record(records[1]),
        Leaf::from_record(records[2]),
    ];
    let region_root_0 = region_root(&mut leaves, &ladder);

    // Region slot 1 is touched by the epoch but not edited: an empty region is the ladder's top, and
    // it must not be confused with an empty list.
    let region_root_1 = ladder.empty(12);

    let mut slot_buffer: [Root; 2] = [[0; 32]; 2];
    let slot_rows = slot_leaves(&SLOTS, &mut slot_buffer).expect("two rows, two slots");
    let slot_table = list_root(slot_rows);

    let mut region_buffer: [Root; 2] = [[0; 32]; 2];
    region_buffer[0] = region_leaf(0, &region_root_0);
    region_buffer[1] = region_leaf(1, &region_root_1);
    let regions = list_root(&region_buffer);

    // One event, plus the empty-list case, because the two must not share a digest.
    let event = event_leaf(1, &[0x01, 0x02]);
    let events = list_root(&[event]);
    let no_events = list_root(&[]);

    let header = EpochHeader {
        epoch_index: 0,
        base_genesis_root: genesis,
        event_log_root: events,
        region_slots: &SLOTS,
        record_count: 3,
    };
    let epoch = epoch_root(&header, &slot_table, &regions, &events);

    // Second epoch, same world state, one extra event: a desync has to move the root.
    let events_two = list_root(&[event, event_leaf(2, &[0xFF])]);
    let header_two = EpochHeader {
        epoch_index: 1,
        base_genesis_root: genesis,
        event_log_root: events_two,
        region_slots: &SLOTS,
        record_count: 4,
    };
    let epoch_two = epoch_root(&header_two, &slot_table, &regions, &events_two);

    println!(
        "// generated by `cargo run --release --example root_vectors -p ledger` on this target"
    );
    println!(
        "const EMPTY_0: &str = \"{}\";  // H(kind 2, level 0, empty)",
        hex(&ladder.empty(0))
    );
    println!(
        "const EMPTY_12: &str = \"{}\";  // H(kind 1, level 12, [EMPTY_11; 8])",
        hex(&ladder.empty(12))
    );
    println!(
        "const LEAF_0ABC: &str = \"{}\";  // H(kind 0, level 0, LE_u16(0x0ABC))",
        hex(&voxel_leaf(0x0ABC))
    );
    println!(
        "const LEAF_1FFF_FFFF: &str = \"{}\";  // a u16 wider than 12 bits, masked to 0x0FFF",
        hex(&voxel_leaf(0xFFFF))
    );
    println!("const GENESIS: &str = \"{}\";  // H(kind 10, 0, seed 0x5EED000000000001, rule 0, version 0)", hex(&genesis));
    println!(
        "const SLOT_LEAF_0: &str = \"{}\";  // H(kind 7, 0, slot 0, (0, 0, 0))",
        hex(&slot_rows[0])
    );
    println!(
        "const SLOT_LEAF_1: &str = \"{}\";  // H(kind 7, 0, slot 1, (-1, 2, 0))",
        hex(&slot_rows[1])
    );
    println!(
        "const SLOT_TABLE: &str = \"{}\";  // list over SLOT_LEAF_0, SLOT_LEAF_1",
        hex(&slot_table)
    );
    println!(
        "const REGION_0: &str = \"{}\";  // three edits, arrival order, walk-sorted",
        hex(&region_root_0)
    );
    println!(
        "const REGION_1: &str = \"{}\";  // no edits: the empty ladder's top",
        hex(&region_root_1)
    );
    println!(
        "const REGIONS: &str = \"{}\";  // list over the two region leaves",
        hex(&regions)
    );
    println!(
        "const EVENTS_ONE: &str = \"{}\";  // one-item list, not wrapped",
        hex(&events)
    );
    println!(
        "const EVENTS_EMPTY: &str = \"{}\";  // H(kind 3, 0, empty)",
        hex(&no_events)
    );
    println!(
        "const EVENTS_TWO: &str = \"{}\";  // list over tag 1 and tag 2",
        hex(&events_two)
    );
    println!(
        "const EPOCH_0: &str = \"{}\";  // the root a peer sends",
        hex(&epoch)
    );
    println!(
        "const EPOCH_1: &str = \"{}\";  // same world, one more event, epoch_index 1",
        hex(&epoch_two)
    );
}
